static int language_valid(const char *language)
{
    return language &&
           (strcmp(language, UI_LANG_EN) == 0 ||
            strcmp(language, UI_LANG_ZH) == 0 ||
            strcmp(language, UI_LANG_JA) == 0);
}

void ui_i18n_init(void)
{
    char value[sizeof(ui_language)];

    ui_prefs_get(UI_LANGUAGE_KEY, value, sizeof(value), UI_LANG_EN);
    if(!language_valid(value)) {
        snprintf(value, sizeof(value), "%s", UI_LANG_EN);
    }
    snprintf(ui_language, sizeof(ui_language), "%s", value);
}

const char *ui_i18n_language(void)
{
    return ui_language;
}

int ui_i18n_is_chinese(void)
{
    return strcmp(ui_language, UI_LANG_ZH) == 0;
}

int ui_i18n_is_japanese(void)
{
    return strcmp(ui_language, UI_LANG_JA) == 0;
}

int ui_i18n_set_language(const char *language)
{
    if(!language_valid(language)) {
        language = UI_LANG_EN;
    }

    snprintf(ui_language, sizeof(ui_language), "%s", language);
    return ui_prefs_set(UI_LANGUAGE_KEY, ui_language);
}

const char *ui_tr(const char *text)
{
    if(!text || (!ui_i18n_is_chinese() && !ui_i18n_is_japanese())) {
        return text ? text : "";
    }

    for(size_t i = 0; i < sizeof(ui_translations) / sizeof(ui_translations[0]); i++) {
        if(strcmp(ui_translations[i].key, text) == 0) {
            const char *translated = ui_i18n_is_japanese() ?
                                     ui_translations[i].ja :
                                     ui_translations[i].zh;
            if(translated && translated[0]) {
                return translated;
            }
            return text;
        }
    }

    return text;
}
